def plural(n: int, one: str, few: str, many: str) -> str:
    """Форма слова к числу: 1 час, 2 часа, 5 часов, 11 часов, 21 час.

    Числа в текстах приходят из настроек салона, так что «за 1 часа» вылезет
    у первого же заказчика, который поменяет срок. Отдельным модулем, потому что
    нужна и repo, и text, а text сам импортирует repo.
    """
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many
